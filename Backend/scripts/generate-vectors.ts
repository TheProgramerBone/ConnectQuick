const dir = fileURLToPath(new URL("../../Protocol/test-vectors/", import.meta.url));
const crypto = JSON.parse(readFileSync(`${dir}crypto-vectors.json`, "utf8")) as {
  identities: Record<string, { privateJwkD: string; publicKeyB64Url: string; expectedDeviceId: string }>;
};

function ed25519Sign(d: string, x: string, message: Buffer): string {
  const key = createPrivateKey({ key: { kty: "OKP", crv: "Ed25519", d, x }, format: "jwk" });
  return sign(null, message, key).toString("base64url");
}

export function buildSessionVectors(): object {
  const host = crypto.identities["host"]!;
  const controller = crypto.identities["controller"]!;
  const controllerEphPriv = Buffer.alloc(32, 0x11).toString("base64url");
  const hostEphPriv = Buffer.alloc(32, 0x22).toString("base64url");
  const cEph = ephemeralFromRaw(controllerEphPriv, x25519PublicFromPrivate(controllerEphPriv));
  const hEph = ephemeralFromRaw(hostEphPriv, x25519PublicFromPrivate(hostEphPriv));
  const sessionId = "6f1d6b5a-3a56-4c42-9d7e-0c1f2a3b4c5d";
  const issuedAt = 1_760_000_000_000;
  const permissions = ["remote_desktop", "mouse", "keyboard", "clipboard"];

  const connectMsg = sessionConnectMessage(sessionId, host.expectedDeviceId, controller.expectedDeviceId, cEph.publicB64Url, issuedAt);
  const acceptMsg = sessionAcceptMessage(sessionId, host.expectedDeviceId, controller.expectedDeviceId, cEph.publicB64Url, hEph.publicB64Url, permissions);
  const transcript = transcriptHash(sessionId, host.expectedDeviceId, controller.expectedDeviceId, cEph.publicB64Url, hEph.publicB64Url, permissions);
  const shared = sharedSecret(cEph, hEph.publicB64Url);
  const sharedFromHost = sharedSecret(hEph, cEph.publicB64Url);
  if (!shared.equals(sharedFromHost)) throw new Error("X25519 asymmetric?!");
  const keys = deriveSessionKeys(shared, transcript);

  const frames: { direction: string; seq: number; plaintext: string; ct: string }[] = [];
  const plain = [
    ["c2h", 0, '{"t":"ctl.ping","n":1}'],
    ["c2h", 1, '{"t":"input.mouse_move","dx":-12,"dy":7}'],
    ["h2c", 0, '{"t":"ctl.caps","hostVersion":"0.2.0","permissions":["mouse"],"features":["input"]}'],
    ["c2h", 255, '{"t":"input.text","text":"ñandú ✓ 🙂"}'],
    ["h2c", 4294967295, '{"t":"ctl.pong","n":2}'],
  ] as const;
  for (const [direction, seq, plaintext] of plain) {
    const ch = direction === "c2h" ? SessionChannel.forController(sessionId, keys) : SessionChannel.forHost(sessionId, keys);
    frames.push({ direction, seq, plaintext, ct: ch.seal(plaintext, seq).ct });
  }

  return {
    $comment:
      "Generated by Backend/scripts/generate-vectors.ts from the TypeScript reference. Every platform must reproduce each derived value from the inputs, and must open every frame.",
    identities: {
      host: { ...host },
      controller: { ...controller },
    },
    ephemeral: {
      controller: { privateB64Url: controllerEphPriv, publicB64Url: cEph.publicB64Url },
      host: { privateB64Url: hostEphPriv, publicB64Url: hEph.publicB64Url },
    },
    session: { sessionId, issuedAt, permissions },
    expected: {
      connectMessage: connectMsg.toString("utf8"),
      connectSigB64Url: ed25519Sign(controller.privateJwkD, controller.publicKeyB64Url, connectMsg),
      acceptMessage: acceptMsg.toString("utf8"),
      acceptSigB64Url: ed25519Sign(host.privateJwkD, host.publicKeyB64Url, acceptMsg),
      sharedSecretB64Url: shared.toString("base64url"),
      transcriptSha256B64Url: transcript.toString("base64url"),
      keyC2HB64Url: keys.c2h.toString("base64url"),
      keyH2CB64Url: keys.h2c.toString("base64url"),
    },
    frames,
    negative: {
      $comment: "Opening any of these MUST fail.",
      tamperedFrame: { direction: "c2h", seq: 1, ctWithFlippedBit: flipFirstBit(frames[1]!.ct) },
      wrongDirection: { sealedAs: "c2h", seq: 0, openedAs: "h2c", ct: frames[0]!.ct },
      wrongSeq: { direction: "c2h", sealedSeq: 1, presentedSeq: 2, ct: frames[1]!.ct },
    },
  };
}

function flipFirstBit(ct: string): string {
  const raw = Buffer.from(ct, "base64url");
  raw[0] = raw[0]! ^ 1;
  return raw.toString("base64url");
}

const U = "6f1d6b5a-3a56-4c42-9d7e-0c1f2a3b4c5d";
