/**
 * The Android/JVM implementation must reproduce every value in Protocol/test-vectors/session-vectors.json,
 * generated by the TypeScript reference. Passing here means a Controller and a Host (or the reference
 * peer) derive the same keys and can open each other's frames.
 */
class SessionVectorsTest {
    private val v = TestFiles.vectors("session-vectors.json")
    private val ids = v.getValue("identities").jsonObject
    private val session = v.getValue("session").jsonObject
    private val eph = v.getValue("ephemeral").jsonObject
    private val expected = v.getValue("expected").jsonObject
    private val permissions = session.getValue("permissions").jsonArray.map { it.jsonPrimitive.content }
    private val sessionId = session.str("sessionId")
    private val hostId = ids.getValue("host").str("expectedDeviceId")
    private val deviceId = ids.getValue("controller").str("expectedDeviceId")
    private val cPub = eph.getValue("controller").str("publicB64Url")
    private val hPub = eph.getValue("host").str("publicB64Url")

    private fun ephemeral(who: String) = SessionCrypto.Ephemeral(CryptoUtil.fromBase64Url(eph.getValue(who).str("privateB64Url")))

    private fun keys(): SessionCrypto.Keys {
        val transcript = SessionCrypto.transcriptHash(sessionId, hostId, deviceId, cPub, hPub, permissions)
        return SessionCrypto.deriveKeys(SessionCrypto.sharedSecret(ephemeral("controller"), hPub), transcript)
    }

    @Test
    fun public_keys_derive_from_the_private_seeds() {
        assertEquals(cPub, ephemeral("controller").publicB64Url)
        assertEquals(hPub, ephemeral("host").publicB64Url)
    }

    @Test
    fun signed_messages_and_signatures_match_the_reference() {
        val connect = SessionCrypto.connectMessage(sessionId, hostId, deviceId, cPub, session.getValue("issuedAt").jsonPrimitive.longOrNull!!)
        assertEquals(expected.str("connectMessage"), String(connect, Charsets.UTF_8))
        val controller = CryptoUtil.ed25519KeyPairFromSeed(CryptoUtil.fromBase64Url(ids.getValue("controller").str("privateJwkD")))
        assertEquals(expected.str("connectSigB64Url"), controller.sign(connect))

        val accept = SessionCrypto.acceptMessage(sessionId, hostId, deviceId, cPub, hPub, permissions)
        assertEquals(expected.str("acceptMessage"), String(accept, Charsets.UTF_8))
        val host = CryptoUtil.ed25519KeyPairFromSeed(CryptoUtil.fromBase64Url(ids.getValue("host").str("privateJwkD")))
        assertEquals(expected.str("acceptSigB64Url"), host.sign(accept))
        assertTrue(CryptoUtil.verifyEd25519(ids.getValue("host").str("publicKeyB64Url"), accept, expected.str("acceptSigB64Url")))
    }

    @Test
    fun shared_secret_and_keys_match_and_both_sides_agree() {
        val k = keys()
        assertEquals(expected.str("keyC2HB64Url"), CryptoUtil.toBase64Url(k.c2h))
        assertEquals(expected.str("keyH2CB64Url"), CryptoUtil.toBase64Url(k.h2c))
        assertEquals(expected.str("sharedSecretB64Url"), CryptoUtil.toBase64Url(SessionCrypto.sharedSecret(ephemeral("host"), cPub)))
    }

    @Test
    fun every_reference_frame_opens_and_our_own_sealing_reproduces_it() {
        val k = keys()
        for (f in v.getValue("frames").jsonArray) {
            val c2h = f.str("direction") == "c2h"
            val receiver = if (c2h) SessionChannel.forHost(sessionId, k) else SessionChannel.forController(sessionId, k)
            val sender = if (c2h) SessionChannel.forController(sessionId, k) else SessionChannel.forHost(sessionId, k)
            val seq = f.jsonObject.getValue("seq").jsonPrimitive.longOrNull!!
            assertEquals(f.str("plaintext"), String(receiver.open(seq, f.str("ct")), Charsets.UTF_8))
            assertEquals(f.str("ct"), sender.seal(f.str("plaintext").toByteArray(Charsets.UTF_8), seq).ct)
        }
    }

    private fun rejected(block: () -> Unit) = try { block(); fail("expected the frame to be rejected") } catch (e: FrameRejected) { /* expected */ }

    @Test
    fun tampered_reflected_and_resequenced_frames_are_rejected() {
        val k = keys()
        val neg = v.getValue("negative").jsonObject
        val t = neg.getValue("tamperedFrame").jsonObject
        rejected { SessionChannel.forHost(sessionId, k).open(t.getValue("seq").jsonPrimitive.longOrNull!!, t.str("ctWithFlippedBit")) }
        val r = neg.getValue("wrongDirection").jsonObject
        rejected { SessionChannel.forController(sessionId, k).open(r.getValue("seq").jsonPrimitive.longOrNull!!, r.str("ct")) }
        val w = neg.getValue("wrongSeq").jsonObject
        rejected { SessionChannel.forHost(sessionId, k).open(w.getValue("presentedSeq").jsonPrimitive.longOrNull!!, w.str("ct")) }
    }

    @Test
    fun replays_and_out_of_order_frames_are_rejected_after_a_valid_one() {
        val k = keys()
        val tx = SessionChannel.forController(sessionId, k)
        val rx = SessionChannel.forHost(sessionId, k)
        val a = tx.seal("{}".toByteArray())
        val b = tx.seal("{}".toByteArray())
        rx.open(b.seq, b.ct)
        rejected { rx.open(a.seq, a.ct) }
        rejected { rx.open(b.seq, b.ct) }
        try { tx.seal("{}".toByteArray(), 4294967296L); fail("sequence space must be bounded") } catch (e: IllegalStateException) { }
    }

    @Test
    fun a_different_permission_list_yields_different_keys_so_a_mitm_cannot_upgrade_grants() {
        val honest = keys()
        val upgraded = SessionCrypto.deriveKeys(
            SessionCrypto.sharedSecret(ephemeral("controller"), hPub),
            SessionCrypto.transcriptHash(sessionId, hostId, deviceId, cPub, hPub, permissions + "power"),
        )
        assertNotEquals(CryptoUtil.toBase64Url(honest.c2h), CryptoUtil.toBase64Url(upgraded.c2h))
    }

    @Test
    fun a_low_order_peer_key_is_refused() {
        val own = SessionCrypto.generateEphemeral()
        try { SessionCrypto.sharedSecret(own, CryptoUtil.toBase64Url(ByteArray(32))); fail("all-zero key must be refused") } catch (e: java.security.GeneralSecurityException) { }
        try { SessionCrypto.sharedSecret(own, CryptoUtil.toBase64Url(ByteArray(16))); fail("short key must be refused") } catch (e: IllegalArgumentException) { }
    }
}

class InnerMessageVectorsTest {
    private val v = TestFiles.vectors("inner-message-vectors.json")

    private val classOf = mapOf(
        "too_large" to InnerRejection.TOO_LARGE, "malformed_json" to InnerRejection.MALFORMED_JSON,
        "not_an_object" to InnerRejection.NOT_AN_OBJECT, "missing_type" to InnerRejection.MISSING_TYPE,
        "unknown_type" to InnerRejection.UNKNOWN_TYPE, "schema" to InnerRejection.SCHEMA,
    )

    @Test
    fun every_valid_message_is_accepted() {
        val valid = v.getValue("valid").jsonArray
        assertTrue(valid.size >= 40)
        for (m in valid) {
            val r = InnerMessages.parse(m.str("json"))
            assertTrue("${m.str("name")} => ${r.rejection}", r.ok)
        }
    }

    @Test
    fun every_invalid_message_is_rejected_with_the_same_class_as_the_reference() {
        val invalid = v.getValue("invalid").jsonArray
        assertTrue(invalid.size >= 40)
        for (m in invalid) {
            val r = InnerMessages.parse(m.str("json"))
            assertEquals(m.str("name"), classOf.getValue(m.str("reason")), r.rejection)
        }
    }

    @Test
    fun every_type_in_the_schema_has_a_valid_vector() {
        val covered = v.getValue("valid").jsonArray.map { InnerMessages.parse(it.str("json")).type }.toSet()
        for (t in InnerMessages.knownTypes) assertTrue("no valid vector for $t", t in covered)
    }

    @Test
    fun serialize_enforces_the_size_limit_before_encryption() {
        try {
            InnerMessages.serialize("rtc.offer") { put("sdp", kotlinx.serialization.json.JsonPrimitive("x".repeat(InnerMessages.MAX_INNER_BYTES))) }
            fail("oversized message must not be serialisable")
        } catch (e: IllegalStateException) { }
    }

    @Test
    fun deeply_nested_documents_are_rejected_without_blowing_the_stack() {
        val r = InnerMessages.parse("[".repeat(30_000) + "]".repeat(30_000))
        assertFalse(r.ok)
    }

    @Test
    fun invalid_utf8_is_malformed_not_repaired() {
        val bytes = "{\"t\":\"ctl.ping\",\"n\":1}".toByteArray() + byteArrayOf(0xC3.toByte())
        assertEquals(InnerRejection.MALFORMED_JSON, InnerMessages.parse(bytes).rejection)
    }
}
